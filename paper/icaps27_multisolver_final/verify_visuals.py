"""Visual-asset consistency check for the restructured manuscript (Phase 6).

Checks, for every figure generated by this directory's make_figure*.py
scripts and referenced from manuscript.tex:
  1. the figure file exists;
  2. its generating script exists;
  3. every source data file the script reads exists;
  4. every method label the script's ORDER/labels reference is a real
     comparison key in confirmatory_analysis.json (no invented comparator);
  5. metric names used ("pi") match the registry key present in that JSON;
  6. CI values plotted are derived with the same denominator as the mean
     (the unit-mismatch bug class found and fixed during Phase 2) -- checked
     by recomputing from the JSON exactly as the figure script does and
     diffing;
  7. heatmap/table cell values recomputed independently from the JSON match
     the script's own printed output exactly;
  8. the figure PDF on disk is not older than its generating script or the
     source JSON (stale-figure detection);
  9. every macro used in manuscript.tex (per check_claims.py's claim
     registry) resolves in numbers.tex -- delegates to check_claims.py;
  10. every figure label referenced by \\ref in manuscript.tex corresponds to
      a \\label actually defined (figure/table-to-claim/text matching).

Exits 1 and prints every failure if any check fails.

    .venv/bin/python paper/icaps27_unified_visual/verify_visuals.py
"""
import json
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
FIGDIR = HERE / "figures"
CONF_PATH = ROOT / "results/unified_icaps/confirmatory/confirmatory_analysis.json"
conf = json.loads(CONF_PATH.read_text())

failures = []


def fail(msg):
    failures.append(msg)


# --- 1/2/3: figure, script, and declared source files exist ---
FIGURES = {
    "forest_u1.pdf": "make_figure4_forest.py",
    "mechanism_u2_u1.pdf": "make_figure5_mechanism.py",
    "robustness_heatmap.pdf": "make_figure6_heatmap.py",
}
MECH_PATH = ROOT / "results/multisolver/audit/mechanism_reproduction.json"
MS_ANALYSIS = ROOT / "results/multisolver/analysis/heldout.json"
MS_GEN = ROOT / "scripts/multisolver/generate_figures.py"
MS_FIGS = ["ms/s1_engines_cold.pdf", "ms/s2_trajectories.pdf", "ms/s34_within_solver.pdf",
           "ms/s4b_stage_attribution.pdf", "ms/s5_scalability.pdf", "ms/s6_model_overhead.pdf"]
for fig, script in FIGURES.items():
    fig_p, script_p = FIGDIR / fig, FIGDIR / script
    if not fig_p.exists():
        fail(f"missing figure: {fig_p}")
    if not script_p.exists():
        fail(f"missing generating script: {script_p}")
        continue
    text = script_p.read_text()
    for m in re.finditer(r'ROOT\s*/\s*"([^"]+)"', text):
        src = ROOT / m.group(1)
        if not src.exists():
            fail(f"{script}: declared source file does not exist: {src}")
    # 8: staleness -- figure must not be older than its script or the shared source JSON
    if fig_p.exists():
        fig_mtime = fig_p.stat().st_mtime
        if script_p.stat().st_mtime > fig_mtime:
            fail(f"STALE: {fig} is older than {script} (regenerate)")
        if CONF_PATH.exists() and CONF_PATH.stat().st_mtime > fig_mtime:
            fail(f"STALE: {fig} is older than {CONF_PATH.name} (regenerate)")
        if script == "make_figure5_mechanism.py" and MECH_PATH.stat().st_mtime > fig_mtime:
            fail(f"STALE: {fig} is older than {MECH_PATH.name} (regenerate)")

# cross-solver figures: exist, generated by the multisolver script, not older than the analysis
tex_now = (HERE / "manuscript.tex").read_text()
for rel in MS_FIGS:
    fp = FIGDIR / rel
    if f"figures/{rel}" not in tex_now:
        continue                       # only figures the manuscript actually includes are required
    if not fp.exists():
        fail(f"missing cross-solver figure: {fp}")
        continue
    if not MS_ANALYSIS.exists():
        fail(f"{rel}: its evidence file {MS_ANALYSIS} does not exist")
    elif MS_ANALYSIS.stat().st_mtime > fp.stat().st_mtime or MS_GEN.stat().st_mtime > fp.stat().st_mtime:
        fail(f"STALE: {rel} is older than the multisolver analysis or its generator (regenerate)")
for rel in re.findall(r"\\input\{(figures/ms/tables/[^}]+)\}", tex_now):
    if not (HERE / (rel if rel.endswith(".tex") else rel + ".tex")).exists():
        fail(f"missing generated table {rel}")

# --- 4/5: method labels and metric used by each figure script are real keys ---
ALL_COMPARISON_KEYS = {
    (setting, k) for setting, s in conf["settings"].items() for k in s["comparisons"]
}
ALL_SETTINGS = set(conf["settings"])


def check_keys(script_name, setting_key_pairs):
    for setting, key in setting_key_pairs:
        if setting not in ALL_SETTINGS:
            fail(f"{script_name}: unknown setting {setting!r}")
            continue
        if key not in conf["settings"][setting]["comparisons"]:
            fail(f"{script_name}: unknown comparison key {key!r} in setting {setting!r}")
        elif "pi" not in conf["settings"][setting]["comparisons"][key]:
            fail(f"{script_name}: comparison {setting}/{key} has no 'pi' metric")


check_keys("make_figure4_forest.py", [
    ("U1_primary", "B2_crit vs B0_iaip"), ("U1_primary", "B2_crit vs B1_random"),
    ("U1_primary", "B2_crit vs B4_prec"), ("U1_primary", "B2_crit vs B3_timewin"),
    ("U1_primary", "B2_crit vs B5_native1w"), ("U1_primary", "B2_crit vs B6_port_hint"),
])
check_keys("make_figure5_mechanism.py", [
    ("U1_primary", "B2_crit vs B3_timewin"), ("U6_arrival", "B2_crit vs B3_timewin"),
    ("U7_outage", "B2_crit vs B3_timewin"), ("U2_mechanism", "M2_crit vs M2_timewin"),
])
check_keys("make_figure6_heatmap.py", [
    (s, "B2_crit vs B0_iaip") for s in
    ["U4_b2", "U1_primary", "U5_b30", "U3_workers4", "U6_arrival", "U7_outage", "U8_high", "U9_benchmarks"]
] + [
    (s, "B2_crit vs B6_port_hint") for s in
    ["U4_b2", "U1_primary", "U5_b30", "U3_workers4", "U6_arrival", "U7_outage", "U8_high", "U9_benchmarks"]
])

# --- 6: CI/mean unit-consistency (the Phase 2 bug class) ---
# For every comparison pulled by any figure script: the CI, scaled by the
# same mean_b denominator as rel_diff, must bracket the point estimate.
for setting, key in ALL_COMPARISON_KEYS:
    c = conf["settings"][setting]["comparisons"][key].get("pi")
    if not c:
        continue
    mean = c["rel_diff"]
    lo, hi = c["ci95"][0] / c["mean_b"], c["ci95"][1] / c["mean_b"]
    if not (min(lo, hi) - 1e-9 <= mean <= max(lo, hi) + 1e-9):
        fail(f"CI does not bracket its own mean once correctly scaled: {setting}/{key} "
             f"mean={mean:.4f} CI=({lo:.4f},{hi:.4f})")

# --- 7: recompute figure 6 cell values independently and diff against the script's own stdout ---
row_map = ["B2_crit vs B0_iaip", "B2_crit vs B6_port_hint"]
col_settings = ["U4_b2", "U1_primary", "U5_b30", "U3_workers4", "U6_arrival", "U7_outage", "U8_high", "U9_benchmarks"]
if (FIGDIR / "make_figure6_heatmap.py").exists():
    out = subprocess.run([sys.executable, str(FIGDIR / "make_figure6_heatmap.py")],
                          capture_output=True, text=True, cwd=FIGDIR)
    if out.returncode != 0:
        fail(f"make_figure6_heatmap.py failed to run: {out.stderr[-500:]}")
    else:
        printed_means = [float(m) for m in re.findall(r"mean=([+-]?\d+\.\d+)%", out.stdout)]
        expected = [100 * conf["settings"][setting]["comparisons"][rkey]["pi"]["rel_diff"]
                    for rkey in row_map for setting in col_settings]
        if len(printed_means) != len(expected):
            fail(f"figure6: expected {len(expected)} printed cells, got {len(printed_means)}")
        else:
            for (setting, rkey), got, want in zip(
                    [(s, r) for r in row_map for s in col_settings], printed_means, expected):
                if abs(got - want) > 0.05:
                    fail(f"figure6 cell mismatch {setting}/{rkey}: script printed {got}%, "
                         f"recomputed from JSON {want:.1f}%")

# --- 9: delegate to check_claims.py (macro resolution, hand-typed literals, staleness) ---
cc = subprocess.run([sys.executable, str(HERE / "check_claims.py")], capture_output=True, text=True, cwd=HERE)
if cc.returncode != 0:
    fail("check_claims.py reported failures:\n" + cc.stdout)

# --- 10: every \ref{...} in manuscript.tex resolves to a \label{...} actually defined ---
tex = (HERE / "manuscript.tex").read_text()
defined_labels = set(re.findall(r"\\label\{([^}]+)\}", tex))
referenced_labels = set(re.findall(r"\\ref\{([^}]+)\}", tex))
dangling = sorted(referenced_labels - defined_labels)
for lbl in dangling:
    fail(f"\\ref{{{lbl}}} has no matching \\label (figure/table/eq reference would render as '??')")

print(f"checks run; failures: {len(failures)}")
for f in failures:
    print("  FAIL:", f)
sys.exit(1 if failures else 0)
