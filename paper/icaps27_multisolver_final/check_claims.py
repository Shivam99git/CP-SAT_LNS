"""Check that every result in manuscript.tex comes from the claim registry.

  1. every macro used in the manuscript that looks like a claim macro
     (starts with S<digit-word> or with a registry prefix) is defined in
     claims.json;
  2. no hand-typed result numbers: outside comments, the text may not
     contain percentages, decimal fractions, W/L ratios or p-values written
     as literals, except in an explicit allow-list of design constants
     (e.g. "8 s", "25%" neighbourhood cap, alpha 0.6) given in ALLOWED;
  3. every claim used in the manuscript is reported with its registry
     metadata in claim_map.md (generated), so a reader can trace each
     number to its source file, setting, algorithm, comparator and metric.

    .venv/bin/python paper/icaps27_cobar/check_claims.py
"""

import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
reg = json.loads((HERE / "claims.json").read_text())
tex = (HERE / "manuscript.tex").read_text()
body = "\n".join(re.sub(r"(?<!\\)%.*", "", line) for line in tex.splitlines())  # unescaped % starts a comment
body = re.sub(r"\\begin\{comment\}.*?\\end\{comment\}", "", body, flags=re.S)

ALLOWED = set(json.loads((HERE / "allowed_literals.json").read_text())) if (HERE / "allowed_literals.json").exists() else set()

used = set(re.findall(r"\\([A-Z][A-Za-z]+)", body))
claim_like = {m for m in used if re.match(r"(UOne|UTwo|UThree|UFour|UFive|USix|USeven|UEight|UNine|Crit|Classification|DevOne|Oracle|MechTwo|RoundsUOne|MTwoRound|FigTwo|RestrStatus|RoundsMOne|RoundsMTwo|RestrSMOne|RestrSMTwo|RestrMTwo|ImprRate|GlobalSM|MS[A-Z])", m)}
undefined = sorted(m for m in claim_like if m not in reg)

patterns = [r"\d+\.\d+\\?%", r"\d+\\?%", r"(?<![\w.])\.\d{3,}", r"\b\d+/\d+\b", r"\d\.\d+\\cdot10\^"]
literal_hits = []
for pat in patterns:
    for m in re.finditer(pat, body):
        s = m.group(0)
        if s in ALLOWED or s.replace("\\%", "%") in ALLOWED:
            continue
        ctx = body[max(0, m.start() - 40): m.end() + 20].replace("\n", " ")
        literal_hits.append((s, ctx))

lines = ["# Claim-to-evidence map (generated by check_claims.py)", "",
         "| Macro | Value | Setting | Algorithm | Comparator | Metric | Statistic | Source |", "|---|---|---|---|---|---|---|---|"]
for m in sorted(claim_like & set(reg)):
    r = reg[m]
    lines.append(f"| `\\{m}` | {r['value']} | {r.get('setting', '')} | {r.get('algorithm', '')} | {r.get('comparator', '')} | "
                 f"{r.get('metric', '')} | {r.get('statistic', '')} | `{r.get('source', '')}` |")
(HERE / "claim_map.md").write_text("\n".join(lines) + "\n")

# --- Phase 9.4 extensions: stale-output and sample-size consistency ---
import subprocess
stale = False
rebuilt = subprocess.run([sys.executable, str(HERE / "make_numbers.py")], cwd=HERE, capture_output=True, text=True)
if rebuilt.returncode == 0:
    fresh_numbers = (HERE / "numbers.tex").read_text()
    # numbers.tex was just overwritten by the rebuild; compare byte-for-byte
    # against what is committed (git diff) to detect staleness.
    diff = subprocess.run(["git", "diff", "--quiet", "--", "numbers.tex"], cwd=HERE)
    tracked = subprocess.run(["git", "ls-files", "--error-unmatch", "numbers.tex"], cwd=HERE,
                             capture_output=True).returncode == 0
    stale = diff.returncode != 0 or not tracked   # an untracked numbers.tex cannot be shown fresh
else:
    print("  WARNING: could not rebuild numbers.tex to check staleness:", rebuilt.stderr[-300:])

sample_size_mismatches = []
conf_path = HERE.parents[1] / "results/unified_icaps/confirmatory/confirmatory_analysis.json"
if conf_path.exists():
    conf = json.loads(conf_path.read_text())
    for setting, sdata in conf["settings"].items():
        tag = {"U1_primary": "UOne", "U2_mechanism": "UTwo", "U3_workers4": "UThree", "U4_b2": "UFour",
               "U5_b30": "UFive", "U6_arrival": "USix", "U7_outage": "USeven", "U8_high": "UEight",
               "U9_benchmarks": "UNine"}.get(setting)
        if tag and f"{tag}N" in reg:
            archived_n = sdata["n_units"]
            macro_n = int(reg[f"{tag}N"]["value"])
            if archived_n != macro_n:
                sample_size_mismatches.append((setting, archived_n, macro_n))

print(f"claim macros used: {len(claim_like)}; undefined: {len(undefined)}; hand-typed result literals: {len(literal_hits)}")
print(f"numbers.tex stale (differs from a fresh rebuild): {stale}")
print(f"sample-size (n_units) mismatches between archived analysis and manuscript macros: {len(sample_size_mismatches)}")
for s_, a_, m_ in sample_size_mismatches:
    print(f"  MISMATCH {s_}: archived n_units={a_} vs manuscript macro={m_}")
for m in undefined:
    print("  UNDEFINED", m)
for s, ctx in literal_hits:
    print(f"  LITERAL {s!r}: ...{ctx}...")
sys.exit(1 if undefined or literal_hits or stale or sample_size_mismatches else 0)
